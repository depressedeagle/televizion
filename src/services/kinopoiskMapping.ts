/**
 * Получить ID КиноПоиска для фильма
 */
export function getKinopoiskId(movie: { id?: string; kinopoiskId?: string; title?: string }): string {
  if (movie.kinopoiskId && movie.kinopoiskId.trim()) {
    return movie.kinopoiskId.trim()
  }

  if (movie.id && REZKA_KINOPOISK_MAP[movie.id]) {
    return REZKA_KINOPOISK_MAP[movie.id]
  }

  // Если нет явного соответствия, возвращаем пустую строку (плеер будет искать по названию)
  return ''
}
